import yfinance as yf
import pandas as pd
import matplotlib.pyplot as plt
from arch import arch_model

# Download NVDA data
data = yf.download("NVDA", start="2023-11-01", end="2024-09-30")

# Compute daily returns (%)
returns = 100 * data['Close'].pct_change().dropna()

returns.plot(figsize=(10,4), title="NVIDIA Daily Returns")
plt.show()

# Fit GARCH(1,1)
model = arch_model(returns, vol='GARCH', p=1, q=1)
res = model.fit(disp='off')

# Model summary
print(res.summary())

# Forecast next 5 days
forecast = res.forecast(horizon=5)
volatility = forecast.variance[-1:] ** 0.5

print("\n5-Day Volatility Forecast (%):")
print(volatility)

plt.figure(figsize=(10,5))
plt.plot(res.conditional_volatility, label="Estimated Volatility")
plt.title("NVDA - GARCH(1,1) Volatility (Nov 2023 - Sep 2024)")
plt.xlabel("Date")
plt.ylabel("Volatility (%)")
plt.legend()
plt.show()